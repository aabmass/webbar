//! Generates `preload/src/generated/sway.ts` from Sway's IPC reply types.
//!
//! `swayipc-types` only derives serde, and Rust's orphan rule prevents adding
//! `ts_rs::TS` to foreign types. Instead we trace the types' `Deserialize`
//! impls with `serde-reflection` and emit TypeScript from the resulting
//! registry. The output therefore matches exactly what serde puts on the wire.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use serde_reflection::{
    ContainerFormat, Format, Named, Registry, Samples, Tracer, TracerConfig, VariantFormat,
};

#[path = "src/sway_state.rs"]
#[allow(dead_code)]
mod sway_state;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/sway_state.rs");
    println!("cargo:rerun-if-env-changed=WEBBAR_TS_DIR");

    let Some(out_dir) = output_dir() else {
        // e.g. the Nix package build, whose source set has no preload/ dir.
        return;
    };

    let registry = trace();
    let ts = render(&registry);

    fs::create_dir_all(&out_dir).expect("create TS output dir");
    let path = out_dir.join("sway.ts");
    if fs::read_to_string(&path).ok().as_deref() != Some(ts.as_str()) {
        fs::write(&path, ts).expect("write sway.ts");
    }
}

fn output_dir() -> Option<PathBuf> {
    if let Some(dir) = env::var_os("WEBBAR_TS_DIR") {
        return Some(PathBuf::from(dir));
    }
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR")?);
    let dir = manifest.join("preload/src/generated");
    dir.is_dir().then_some(dir)
}

fn trace() -> Registry {
    use swayipc_types::*;

    let mut tracer = Tracer::new(TracerConfig::default());
    let samples = Samples::new();
    // serde-reflection must see every variant of each enum, which requires
    // tracing enums individually. If swayipc adds an enum reachable from
    // SwayState, `registry()` fails with `MissingVariants(["Name"])`: add it here.
    macro_rules! trace_enums {
        ($($t:ty),* $(,)?) => {
            $( tracer.trace_type::<$t>(&samples).expect(stringify!($t)); )*
        };
    }
    trace_enums!(
        ApplicationIdleInhibitType,
        Floating,
        NodeBorder,
        NodeLayout,
        NodeType,
        Orientation,
        ScratchpadState,
        ShellType,
        UserIdleInhibitType,
    );
    tracer
        .trace_type::<sway_state::SwayState>(&samples)
        .expect("trace SwayState");
    tracer.registry().expect("complete Sway type registry")
}

/// Prefix type names with `Sway` to avoid clashing with DOM globals like `Node`.
fn ts_name(name: &str) -> String {
    if name.starts_with("Sway") {
        name.to_string()
    } else {
        format!("Sway{name}")
    }
}

fn ts_type(format: &Format) -> String {
    match format {
        Format::TypeName(name) => ts_name(name),
        Format::Unit => "null".into(),
        Format::Bool => "boolean".into(),
        Format::I8
        | Format::I16
        | Format::I32
        | Format::I64
        | Format::I128
        | Format::U8
        | Format::U16
        | Format::U32
        | Format::U64
        | Format::U128
        | Format::F32
        | Format::F64 => "number".into(),
        Format::Char | Format::Str => "string".into(),
        Format::Option(inner) => format!("{} | null", ts_type(inner)),
        Format::Seq(inner) => format!("Array<{}>", ts_type(inner)),
        Format::TupleArray { content, .. } => format!("Array<{}>", ts_type(content)),
        Format::Map { key, value } => {
            format!("Record<{}, {}>", ts_type(key), ts_type(value))
        }
        Format::Tuple(items) => {
            let items: Vec<_> = items.iter().map(ts_type).collect();
            format!("[{}]", items.join(", "))
        }
        other => panic!("sway.ts: unsupported serde format {other:?}"),
    }
}

fn render(registry: &Registry) -> String {
    let mut out = String::from(
        "// Generated by build.rs from swayipc-types via serde-reflection. Do not edit.\n",
    );
    for (name, container) in registry {
        let name = ts_name(name);
        out.push('\n');
        match container {
            ContainerFormat::Struct(fields) => {
                writeln!(out, "export type {name} = {{").unwrap();
                for Named { name: field, value } in fields {
                    writeln!(out, "  {field}: {};", ts_type(value)).unwrap();
                }
                out.push_str("};\n");
            }
            ContainerFormat::NewTypeStruct(inner) => {
                writeln!(out, "export type {name} = {};", ts_type(inner)).unwrap();
            }
            ContainerFormat::Enum(variants) => {
                let alts: Vec<String> = variants
                    .values()
                    .map(|Named { name: variant, value }| match value {
                        VariantFormat::Unit => format!("\"{variant}\""),
                        other => panic!("sway.ts: unsupported enum variant {name}::{variant} {other:?}"),
                    })
                    .collect();
                writeln!(out, "export type {name} = {};", alts.join(" | ")).unwrap();
            }
            other => panic!("sway.ts: unsupported container {name} {other:?}"),
        }
    }
    out
}
